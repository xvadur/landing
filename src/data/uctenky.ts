const INDEX = new Map(UCTENKY.map((u) => [u.kluc, u]));

/** Účtenka podľa kľúča. Chýbajúci kľúč = chyba pri builde (žiadne vymyslené číslo neprejde). */
export function uctenka(kluc: string): Uctenka {
  const u = INDEX.get(kluc);
  if (!u) throw new Error(`uctenky.ts: neznámy kľúč „${kluc}" — číslo bez účtenky na web nejde`);
  return u;
}

/** Účtenka podľa kľúča alebo undefined (na podmienené vykreslenie). */
export function uctenkaOpt(kluc: string): Uctenka | undefined {
  return INDEX.get(kluc);
}

/** Číselná hodnota účtenky; text / V OPRAVE → chyba (staviteľ má použiť `formatHodnota`). */
export function cislo(kluc: string): number {
  const u = uctenka(kluc);
  if (typeof u.hodnota !== 'number') throw new Error(`uctenky.ts: „${kluc}" nie je číslo (${PECIATKA_LABEL[u.peciatka]})`);
  return u.hodnota;
}

/** Účtenky jednej oblasti v poradí súboru. */
export function uctenkyOblasti(oblast: Oblast): Uctenka[] {
  return UCTENKY.filter((u) => u.oblast === oblast);
}

/** Smie sa zobraziť? `kde` začínajúce „NIKDE" = nie (súhlas / ratifikácia chýba). */
export function naWeb(u: Uctenka): boolean {
  return !/^NIKDE/i.test(u.kde);
}

const NBSP = ' ';

/** Slovenský zápis čísla: tisícové skupiny pevnou medzerou (U+00A0), desatinná čiarka.
 *  formatCislo(28579326) → „28 579 326"; formatCislo(0.865, 3) → „0,865"; formatCislo(37.5) → „37,5".
 *  `desatinne` = pevný počet desatinných miest; bez neho sa nechá toľko, koľko číslo má (max 3). */
export function formatCislo(n: number, desatinne?: number): string {
  if (!Number.isFinite(n)) return '—';
  const neg = n < 0;
  const abs = Math.abs(n);
  const fixed = desatinne == null ? String(Math.round(abs * 1000) / 1000) : abs.toFixed(desatinne);
  const [cela, des] = fixed.split('.');
  const skupiny = cela!.replace(/\B(?=(\d{3})+(?!\d))/g, NBSP);
  return `${neg ? '−' : ''}${skupiny}${des ? `,${des}` : ''}`;
}

/** ISO dátum → slovenský zápis s pevnými medzerami: 2026-09-20 → „20. 9. 2026"; 2026-09 → „9/2026"; iný text ostáva. */
export function formatDatum(iso: string): string {
  const m = /^(\d{4})-(\d{2})(?:-(\d{2}))?$/.exec(iso);
  if (!m) return iso;
  const [, r, mes, d] = m;
  const mm = String(Number(mes));
  return d ? `${Number(d)}.${NBSP}${mm}.${NBSP}${r}` : `${mm}/${r}`;
}

/** Hodnota účtenky pripravená na výpis (bez jednotky): číslo so slovenskými medzerami, dátum po slovensky,
 *  text / rozsah verbatim, prázdna V OPRAVE → „—". */
export function formatHodnota(u: Uctenka): string {
  if (u.hodnota === '' || u.hodnota == null) return '—';
  if (typeof u.hodnota === 'number') return formatCislo(u.hodnota);
  if (u.format === 'datum') return formatDatum(u.hodnota);
  return u.hodnota;
}

/** Hodnota + jednotka („28 579 326 krokov", „37,5 %", „300 €"). */
export function hodnotaText(kluc: string): string {
  const u = uctenka(kluc);
  const h = formatHodnota(u);
  return u.jednotka ? `${h}${NBSP}${u.jednotka}` : h;
}

/** Mono riadok pod číslom: „zdroj · k dátumu" (skrátený zdroj = časť za posledným lomítkom, ak je dlhý). */
export function zdrojRiadok(u: Uctenka): string {
  const z = u.zdroj.length > 72 ? u.zdroj.replace(/^.*\/(?=[^/]+$)/, '') : u.zdroj;
  return `${z} · k ${formatDatum(u.kDatumu)}`;
}
